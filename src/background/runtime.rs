/// Idle timeouts per category, resolved once from config at construction.
///
/// Like `max_concurrent`, these are fixed for the lifetime of the runtime —
/// a config reload updates `SpawnContext.background_config` for tier
/// resolution but does not resize this runtime, the same limitation
/// `max_concurrent` already has today.
#[derive(Debug, Clone, Copy)]
pub(crate) struct IdleTimeouts {
    scheduled: Duration,
    spawned: Duration,
    external: Duration,
}

impl IdleTimeouts {
    /// Resolve the idle timeout for a session, given its trigger.
    ///
    /// Webhook sessions are `external` but use the `scheduled` timeout: a
    /// webhook call is one-shot with no expected back-and-forth.
    fn for_trigger(&self, trigger: &EventTrigger) -> Duration {
        match SessionCategory::from_trigger(trigger) {
            SessionCategory::Scheduled => self.scheduled,
            SessionCategory::Spawned => self.spawned,
            SessionCategory::External => {
                if matches!(trigger, EventTrigger::Webhook(_)) {
                    self.scheduled
                } else {
                    self.external
                }
            }
        }
    }
}

impl From<&BackgroundConfig> for IdleTimeouts {
    fn from(cfg: &BackgroundConfig) -> Self {
        Self {
            scheduled: cfg.idle_timeout_scheduled,
            spawned: cfg.idle_timeout_spawned,
            external: cfg.idle_timeout_external,
        }
    }
}

/// A request to fork a new session run.
pub(crate) struct SessionSpawnRequest {
    /// Address the session runs under (pre-generated by the caller).
    pub address: SessionAddress,
    /// Human-readable source label (e.g. `"pulse:email_check"`).
    pub source_label: String,
    /// What triggered this session.
    pub trigger: EventTrigger,
    /// Skill the session runs with, if any.
    pub agent_skill: Option<SkillName>,
    /// The agent that requested this spawn, if any (see [`SpawnRequestEvent`]
    /// via [`crate::bus::SpawnRequestEvent`]).
    pub spawner: Option<SessionAddress>,
    /// Depth from the main agent this session runs at (main = 0).
    pub depth: u32,
    /// The session's turn configuration.
    pub subagent_config: SubAgentConfig,
    /// The conversation this session replies to, for a conversation-triggered
    /// session. `None` for every other trigger.
    pub conversation_target: Option<ConversationTarget>,
}

/// Executes session turns with bounded concurrency, tracking each session's
/// lifecycle in the registry and its record in the store.
pub struct SessionRuntime {
    semaphore: Arc<Semaphore>,
    registry: Arc<SessionRegistry>,
    store: Arc<SessionStore>,
    idle_timeouts: IdleTimeouts,
    publisher: Publisher,
    tz: chrono_tz::Tz,
    /// Used only to resume a run whose interrupt channel still held agent
    /// messages at the moment its own teardown drained it — see
    /// `finish_run`. Ordinary live delivery goes through the registry
    /// directly and never touches this.
    messenger: Arc<AgentMessenger>,
}

/// Shared handles a session run needs for the lifetime of its driver task,
/// grouped to keep [`run_session`]'s signature small.
struct RunEnv {
    semaphore: Arc<Semaphore>,
    registry: Arc<SessionRegistry>,
    store: Arc<SessionStore>,
    publisher: Publisher,
    tz: chrono_tz::Tz,
    messenger: Arc<AgentMessenger>,
}

impl SessionRuntime {
    /// Create a new runtime with the given concurrency limit.
    #[must_use]
    pub(crate) fn new(
        registry: Arc<SessionRegistry>,
        store: Arc<SessionStore>,
        max_concurrent: usize,
        idle_timeouts: impl Into<IdleTimeouts>,
        publisher: Publisher,
        tz: chrono_tz::Tz,
        messenger: Arc<AgentMessenger>,
    ) -> Self {
        Self {
            semaphore: Arc::new(Semaphore::new(max_concurrent)),
            registry,
            store,
            idle_timeouts: idle_timeouts.into(),
            publisher,
            tz,
            messenger,
        }
    }

    /// Fork and run a new session.
    ///
    /// Registers the session as `forking` immediately (so it is discoverable
    /// even before a concurrency permit is available), then drives it through
    /// `running` → `idle` → `completing` → `completed` on a detached task.
    #[tracing::instrument(skip_all, fields(session.address = %req.address))]
    pub(crate) fn spawn(&self, req: SessionSpawnRequest, resources: Option<SubAgentResources>) {
        let run_id = generate_run_id();
        let category = SessionCategory::from_trigger(&req.trigger);
        let purpose = truncate_prompt_preview(&req.subagent_config.prompt);
        let idle_timeout = self.idle_timeouts.for_trigger(&req.trigger);
        let model_tier = req.subagent_config.model_tier;

        let info = SessionInfo {
            address: req.address,
            run_id,
            category,
            trigger: req.trigger,
            source_label: req.source_label,
            state: SessionState::Forking,
            spawner: req.spawner,
            depth: req.depth,
            purpose,
            agent_skill: req.agent_skill,
            model_tier,
            conversation_target: req.conversation_target,
            started_at: Utc::now(),
        };

        let stop_token = CancellationToken::new();
        let interrupt_rx = match self.registry.register(info.clone(), stop_token.clone()) {
            Ok(rx) => rx,
            Err(e) => {
                deliver_losing_spawn_input(&self.registry, &info, &req.subagent_config, &e);
                return;
            }
        };
        tracing::info!(address = %info.address, source_label = %info.source_label, "session forking");

        let env = RunEnv {
            semaphore: Arc::clone(&self.semaphore),
            registry: Arc::clone(&self.registry),
            store: Arc::clone(&self.store),
            publisher: self.publisher.clone(),
            tz: self.tz,
            messenger: Arc::clone(&self.messenger),
        };
        let config = req.subagent_config;

        tokio::spawn(async move {
            publish_session_event(
                &env.publisher,
                &info.address,
                &info.run_id,
                SessionEventKind::Started(Box::new(info.clone())),
            )
            .await;
            env.store.begin_run(&info).await;

            // Cloned up front so cleanup still has something to work with if
            // the task panics — the originals (including `resources`, which
            // is not `Clone`) are moved into `run_session` and gone with it
            // once the panic unwinds past this point.
            let panic_info = info.clone();
            let panic_env = PanicRecoveryEnv {
                registry: Arc::clone(&env.registry),
                store: Arc::clone(&env.store),
                publisher: env.publisher.clone(),
                messenger: Arc::clone(&env.messenger),
                tz: env.tz,
            };
            let mem_extras = resources.as_ref().map(|res| PanicMemoryExtras {
                observer: Arc::clone(&res.observer),
                merge_writer: Arc::clone(&res.merge_writer),
                layout: res.layout.clone(),
                episode_skip_token_floor: res.episode_skip_token_floor,
                hop_counter: res.hop_counter.clone(),
            });

            let outcome = std::panic::AssertUnwindSafe(run_session(
                info,
                config,
                resources,
                stop_token,
                interrupt_rx,
                idle_timeout,
                env,
            ))
            .catch_unwind()
            .await;

            if let Err(panic) = outcome {
                let msg = crate::util::panic_message(&*panic);
                tracing::error!(
                    address = %panic_info.address,
                    run_id = %panic_info.run_id,
                    panic = msg,
                    "session task panicked"
                );
                recover_from_panic(&panic_info, &panic_env, msg, mem_extras).await;
            }
        });
    }

    /// Stop every live session and wait for their runs to finish completing
    /// and being recorded, so a graceful shutdown doesn't leave sessions for
    /// startup recovery to pick up.
    ///
    /// Waits up to `timeout` by polling the registry; logs a warning and
    /// returns if sessions are still live once the deadline passes (their
    /// runs remain in the store as `running` and get swept by startup
    /// recovery on the next boot).
    pub(crate) async fn shutdown(&self, timeout: Duration) {
        let signalled = self.registry.stop_all();
        if signalled == 0 {
            return;
        }
        tracing::info!(sessions = signalled, "stopping live sessions for shutdown");

        let deadline = tokio::time::Instant::now() + timeout;
        while tokio::time::Instant::now() < deadline {
            if self.registry.list_live().is_empty() {
                tracing::info!("all sessions completed for shutdown");
                return;
            }
            tokio::time::sleep(Duration::from_millis(20)).await;
        }
        tracing::warn!(
            remaining = self.registry.list_live().len(),
            "shutdown timed out waiting for live sessions to complete"
        );
    }
}

/// Handle a losing `SessionRegistry::register` call: another attempt already
/// won the compare-and-swap and registered a live run at `info.address` in
/// the meantime (see [`SessionRegistry::register`]'s doc comment for when
/// this can legitimately happen). Rather than drop this run's input on the
/// floor, deliver it into the run that won, the same way a `message_agent`
/// call would.
fn deliver_losing_spawn_input(
    registry: &SessionRegistry,
    info: &SessionInfo,
    config: &SubAgentConfig,
    register_error: &super::registry::RegisterError,
) {
    tracing::error!(
        address = %info.address,
        error = %register_error,
        "refusing to register a session run: address is already live; falling back to \
         delivering its input into the run that won the race"
    );
    // Mirrors `SpawnRequestEvent::kickoff_text` — `config` is already the
    // internal `SubAgentConfig`, not the bus event, so it's built here
    // directly from the same fields.
    let content = match &config.context {
        Some(ctx) => format!("{ctx}\n\n{}", config.prompt),
        None => config.prompt.clone(),
    };
    // Shares `race_guard_interrupt` with `listener::handle_spawn_request`'s
    // own live-address guard: this is the same situation (a spawn/resume's
    // content losing the race for its address), just found in a narrower
    // window — after `handle_spawn_request`'s own check found the address
    // free, but before this run actually won `SessionRegistry::register`. A
    // `Conversation`-triggered run must still deliver its carried inbound
    // message as `Interrupt::UserMessage`, not misattribute it to `main`.
    let outcome = registry.deliver(
        &info.address,
        super::listener::race_guard_interrupt(
            &info.trigger,
            config.inbound.clone(),
            info.spawner.clone(),
            info.category,
            content,
            config.hop_count,
        ),
    );
    match outcome {
        DeliverOutcome::Delivered => {}
        DeliverOutcome::Completing | DeliverOutcome::Full | DeliverOutcome::NotLive => {
            tracing::error!(
                address = %info.address,
                outcome = ?outcome,
                "failed to deliver a spawn's input into the run that won the race; input dropped"
            );
        }
    }
}

/// Handles [`recover_from_panic`] needs beyond a run's own identity, cloned
/// up front from a run's [`RunEnv`] before it moves into [`run_session`] (a
/// panic unwinds through and drops the original, and `RunEnv` itself isn't
/// `Clone`). Grouped into one struct purely to keep `recover_from_panic`'s
/// argument count down.
struct PanicRecoveryEnv {
    registry: Arc<SessionRegistry>,
    store: Arc<SessionStore>,
    publisher: Publisher,
    messenger: Arc<AgentMessenger>,
    tz: chrono_tz::Tz,
}

/// Owned copies of the memory subsystem handles a run's completion pipeline
/// needs, cloned up front (before `resources` moves into [`run_session`])
/// since a panic unwinds through and drops the original `SubAgentResources`
/// — its provider/tools/MCP registry aren't `Clone`, but these three handles
/// are cheap `Arc`/owned clones and are all [`recover_from_panic`] needs to
/// run the same completion pipeline a normal run does.
struct PanicMemoryExtras {
    observer: Arc<crate::memory::observer::Observer>,
    merge_writer: Arc<crate::memory::merge_writer::MemoryMergeWriter>,
    layout: crate::workspace::layout::WorkspaceLayout,
    episode_skip_token_floor: usize,
    /// The run's hop counter at the moment it panicked, cloned so a panicked
    /// spawned session's relay to its spawner (see [`relay_result_to_spawner`])
    /// still carries the right outgoing hop count.
    hop_counter: HopCounter,
}

/// Finalize a session's record and notify listeners after its task panicked,
/// mirroring the cleanup [`run_session`] performs on any other terminal path
/// — otherwise a panic would leave the session `running` forever in the
/// store and permanently registered as live.
///
/// Backfills the transcript from the run's durable `.transcript.jsonl`
/// sidecar (the same file [`RunTranscriptSink`] appended to during the run)
/// and, when the resources for it are available, runs the normal completion
/// memory pipeline over it — a panic mid-turn must not silently drop
/// whatever the run had already produced. The merge writer's own
/// idempotency check (see `crate::memory::merged_run_log`) makes this safe
/// even if the panic happened after a merge had already succeeded.
async fn recover_from_panic(
    info: &SessionInfo,
    env: &PanicRecoveryEnv,
    panic_msg: &str,
    mem_extras: Option<PanicMemoryExtras>,
) {
    transition_state(
        &env.registry,
        &env.publisher,
        info,
        SessionState::Completing,
    )
    .await;
    publish_session_event(
        &env.publisher,
        &info.address,
        &info.run_id,
        SessionEventKind::Error {
            message: format!("session task panicked: {panic_msg}"),
        },
    )
    .await;

    let mut transcript = env
        .store
        .read_incremental_transcript(&info.run_id, info.started_at)
        .await;

    let episode_id = if let Some(extras) = mem_extras.as_ref() {
        let summary = transcript
            .last()
            .map(|m| m.content.clone())
            .unwrap_or_default();
        let mem_env = SessionMemoryEnv {
            observer: extras.observer.as_ref(),
            merge_writer: extras.merge_writer.as_ref(),
            layout: &extras.layout,
            episode_skip_token_floor: extras.episode_skip_token_floor,
            tz: env.tz,
        };
        let tag = crate::memory::types::SourceTag::session(
            info.address.to_string(),
            info.run_id.clone(),
            info.category.as_str(),
        );
        complete_session_memory(tag, &summary, &transcript, SessionMemory::new(), &mem_env).await
    } else {
        None
    };

    let status = AgentResultStatus::Failed {
        error: format!("session task panicked: {panic_msg}"),
    };

    // A panicked turn is exactly the outcome the spawner must never be left
    // not knowing about — relay it the same status-line way any other
    // failed/cancelled turn does (see `maybe_relay_result`), folding the note
    // into the transcript that's about to be finalized rather than a live
    // `RecentMessages` buffer, since this run's own turn loop is gone.
    if info.category == SessionCategory::Spawned
        && let Some(spawner) = info.spawner.clone()
    {
        let hop_count = mem_extras.as_ref().map_or(0, |m| m.hop_counter.outgoing());
        let content = relay_content(&info.address, &status, "");
        let relay_env = RelayEnv {
            messenger: &env.messenger,
            store: &env.store,
            publisher: &env.publisher,
        };
        if let Some(note) =
            relay_result_to_spawner(info, &spawner, &content, hop_count, &relay_env).await
        {
            transcript.push(note);
        }
    }

    env.registry
        .record_resume_point(&info.address, resume_point(info, episode_id.clone()));

    let transcript_path = env
        .store
        .complete_run(
            info,
            SessionState::Completed.as_str(),
            transcript,
            episode_id.clone(),
        )
        .await;

    let event = build_result_event(info, status.clone(), String::new(), transcript_path, env.tz);
    if let Err(e) = env.publisher.publish(topics::Background, event).await {
        tracing::warn!(error = %e, "failed to publish panicked session result to bus");
    }

    env.registry.remove(&info.address, &info.run_id);
    publish_session_event(
        &env.publisher,
        &info.address,
        &info.run_id,
        SessionEventKind::Completed { status, episode_id },
    )
    .await;
    tracing::info!("session removed from registry after panic recovery");
}

/// Build the resume point a completed run leaves behind, so a later
/// `message_agent` call to its address can fork it again with a pointer back
/// to what it produced.
fn resume_point(info: &SessionInfo, episode_id: Option<String>) -> ResumePoint {
    ResumePoint {
        previous_run_id: info.run_id.clone(),
        previous_episode_id: episode_id,
        trigger: info.trigger.clone(),
        source_label: info.source_label.clone(),
        agent_skill: info.agent_skill.clone(),
        model_tier: info.model_tier,
        spawner: info.spawner.clone(),
        depth: info.depth,
        conversation_target: info.conversation_target.clone(),
    }
}

/// Move a run to a new lifecycle state in the registry and announce it on
/// the sessions topic, so every observer (discovery tools, the web UI) sees
/// the same transition.
async fn transition_state(
    registry: &SessionRegistry,
    publisher: &Publisher,
    info: &SessionInfo,
    state: SessionState,
) {
    registry.set_state(&info.address, state);
    publish_session_event(
        publisher,
        &info.address,
        &info.run_id,
        SessionEventKind::StateChanged(state),
    )
    .await;
}

/// What ended a session's idle wait.
enum IdleOutcome {
    /// Stopped via `stop_agent` while idle.
    Stopped,
    /// The idle timeout elapsed with no new input.
    TimedOut,
    /// An agent message arrived; it becomes the next turn's kickoff.
    Woken(AgentMessageEvent),
    /// A new message arrived in this session's conversation; it becomes the
    /// next turn's kickoff.
    WokenExternal(InboundMessage),
}

/// Wait for a session's idle period to end: a stop, the idle timeout, or a
/// message delivered through the run's own interrupt channel (the same
/// channel a running turn drains at its tool-call checkpoints — see
/// `crate::background::messaging`). An interrupt kind other than
/// `AgentMessage`/`UserMessage` is not expected while idle (nothing else is
/// ever sent into a session's channel) but is ignored defensively rather
/// than treated as a wake, so the idle wait keeps going.
async fn wait_idle(
    stop_token: &CancellationToken,
    idle_timeout: Duration,
    interrupt_rx: &mut mpsc::Receiver<Interrupt>,
) -> IdleOutcome {
    loop {
        tokio::select! {
            biased;
            () = stop_token.cancelled() => return IdleOutcome::Stopped,
            () = tokio::time::sleep(idle_timeout) => {
                // `biased` means this arm can win even when a message landed
                // in the channel in the same poll (it's checked ahead of the
                // `recv()` arm below) — a `try_recv` here catches that exact
                // race before treating the run as genuinely timed out and
                // letting its caller move on to completing, which would
                // otherwise leave the message stranded in a channel about to
                // be drained and dropped (see `finish_run`).
                return match interrupt_rx.try_recv() {
                    Ok(Interrupt::AgentMessage(msg)) => IdleOutcome::Woken(msg),
                    Ok(Interrupt::UserMessage(msg)) => IdleOutcome::WokenExternal(msg),
                    Ok(_) | Err(_) => IdleOutcome::TimedOut,
                };
            }
            received = interrupt_rx.recv() => {
                match received {
                    Some(Interrupt::AgentMessage(msg)) => return IdleOutcome::Woken(msg),
                    Some(Interrupt::UserMessage(msg)) => return IdleOutcome::WokenExternal(msg),
                    Some(_) => {}
                    None => return IdleOutcome::TimedOut,
                }
            }
        }
    }
}

/// Everything that happens after a turn finishes, before the run decides
/// whether to linger idle: stage observations past threshold, relay the
/// outcome to a spawned session's spawner, and deliver output to a
/// conversation session's own conversation. Split out of [`run_session`]
/// purely to keep that function's line count down.
async fn after_turn(
    info: &SessionInfo,
    status: &AgentResultStatus,
    summary: &str,
    resources: Option<&SubAgentResources>,
    env: &RunEnv,
    memory: &mut SessionMemory,
    recent_messages: &mut RecentMessages,
) {
    // Per-turn threshold check: mirrors the main agent's own rotation, run
    // after every turn (not just once) since a run can now span several.
    // Staged observations are held locally and merged alongside the final
    // observation on completion.
    if let Some(res) = resources {
        let mem_env = session_memory_env(res, env.tz);
        memory
            .maybe_stage(recent_messages.messages(), &mem_env)
            .await;
    }

    // Relay this turn's outcome to a spawned session's direct spawner, after
    // every turn (not only at run completion) — this generalizes the old
    // one-shot "background task result" relay, and now covers every status
    // (not just a completed turn with output), so the spawner is never left
    // not knowing a turn failed, was cancelled, or produced nothing.
    maybe_relay_result(info, status, summary, resources, env, recent_messages).await;

    // Deliver this turn's output to its own conversation, for a session
    // started by a conversation message. Every other session category has
    // `conversation_target: None` and this is a no-op.
    maybe_output_to_conversation(info, status, summary, env).await;
}

/// Drive one session run from permit acquisition through completion.
///
/// A run is one or more turns: the first is always the fork's task prompt;
/// any later one is an agent message that arrived while the session was
/// idle, per the design's messaging rules. `recent_messages` accumulates
/// across every turn in the run, so a session woken from idle still has its
/// earlier context, and staging/the final merge see the whole run's
/// transcript regardless of how many turns produced it.
#[tracing::instrument(skip_all, fields(session.address = %info.address, run.id = %info.run_id))]
async fn run_session(
    mut info: SessionInfo,
    config: SubAgentConfig,
    resources: Option<SubAgentResources>,
    stop_token: CancellationToken,
    mut interrupt_rx: mpsc::Receiver<Interrupt>,
    idle_timeout: Duration,
    env: RunEnv,
) {
    let mut recent_messages = RecentMessages::new();
    let mut memory = SessionMemory::new();
    let mut kickoff = TurnKickoff::Initial {
        prompt: config.prompt,
        context: config.context,
        hop_count: config.hop_count,
        sender: config.sender,
    };
    // Assigned on the loop's first iteration, which always runs at least
    // once (the run's initial turn), so both are definitely initialized by
    // the time anything after the loop reads them.
    let mut status;
    let mut summary;
    // Numbers this run's turns, for the turn ids its turn events carry.
    let mut turn_number: u32 = 0;

    loop {
        (status, summary) = tokio::select! {
            biased;
            () = stop_token.cancelled() => {
                tracing::info!("session stopped before its turn started");
                (AgentResultStatus::Cancelled, String::new())
            }
            permit = env.semaphore.acquire() => {
                match permit {
                    Ok(_permit) => {
                        transition_state(&env.registry, &env.publisher, &info, SessionState::Running).await;
                        turn_number += 1;
                        let ctx = TurnCtx {
                            info: &info,
                            resources: resources.as_ref(),
                            stop_token: &stop_token,
                            store: &env.store,
                            publisher: &env.publisher,
                        };
                        let turn_id = format!("{}-t{turn_number}", info.run_id);
                        run_turn(&ctx, &turn_id, &mut recent_messages, kickoff, &mut interrupt_rx).await
                    }
                    Err(_closed) => {
                        tracing::warn!("concurrency semaphore closed before session could acquire a permit");
                        (
                            AgentResultStatus::Failed {
                                error: "gateway is shutting down".to_string(),
                            },
                            String::new(),
                        )
                    }
                }
            }
        };

        after_turn(
            &info,
            &status,
            &summary,
            resources.as_ref(),
            &env,
            &mut memory,
            &mut recent_messages,
        )
        .await;

        // A cancelled run — whether stopped before its turn started or
        // mid-turn — skips lingering idle and goes straight to completing,
        // per the design: stopping a session moves it straight to
        // `completing`.
        if matches!(status, AgentResultStatus::Cancelled) {
            tracing::info!("session stopped, skipping idle and completing directly");
            break;
        }

        transition_state(&env.registry, &env.publisher, &info, SessionState::Idle).await;
        tracing::debug!(
            idle_secs = idle_timeout.as_secs(),
            "session idle, awaiting further input or timeout"
        );
        match wait_idle(&stop_token, idle_timeout, &mut interrupt_rx).await {
            IdleOutcome::Stopped => {
                // An explicit stop ends the run early whatever its last turn
                // did, so report it as cancelled; an idle timeout keeps the
                // last turn's own outcome.
                tracing::info!("session stopped while idle");
                status = AgentResultStatus::Cancelled;
                break;
            }
            IdleOutcome::TimedOut => {
                tracing::debug!("session idle timeout elapsed");
                break;
            }
            IdleOutcome::Woken(msg) => {
                tracing::info!(from = %msg.from, "session woken by an agent message, starting another turn");
                kickoff = TurnKickoff::AgentMessage(msg);
            }
            IdleOutcome::WokenExternal(msg) => {
                tracing::info!(msg_id = %msg.id, "session woken by a conversation message, starting another turn");
                kickoff = TurnKickoff::External(msg);
            }
        }
    }

    // The run is genuinely ending now (stopped, or timed out with the race
    // above finding nothing) and `interrupt_rx` is about to be dropped —
    // drain whatever is still queued in it so a message that landed in the
    // narrow window between the loop's last check and here isn't silently
    // lost. `finish_run` resumes the session as a new run to deliver these
    // once this run has fully left the registry.
    let leftover_messages = drain_pending_interrupts(&mut interrupt_rx);

    finish_run(
        &mut info,
        resources.as_ref(),
        RunOutcome {
            status,
            summary,
            memory,
            recent_messages,
            leftover_messages,
        },
        &env,
    )
    .await;
}

/// Drain every agent message or conversation message still queued in a run's
/// interrupt channel, discarding any other interrupt kind (nothing else is
/// ever sent into a session's channel — see `wait_idle`).
fn drain_pending_interrupts(interrupt_rx: &mut mpsc::Receiver<Interrupt>) -> Vec<PendingInput> {
    let mut drained = Vec::new();
    while let Ok(interrupt) = interrupt_rx.try_recv() {
        match interrupt {
            Interrupt::AgentMessage(msg) => drained.push(PendingInput::Agent(msg)),
            Interrupt::UserMessage(msg) => drained.push(PendingInput::External(msg)),
            Interrupt::Subconscious(_) | Interrupt::Stopped => {}
        }
    }
    drained
}

/// What a run's turn loop produced, once it has ended — everything
/// [`finish_run`] needs to close it out, grouped to keep that function's
/// argument count down.
struct RunOutcome {
    status: AgentResultStatus,
    summary: String,
    memory: SessionMemory,
    recent_messages: RecentMessages,
    /// Agent messages and conversation messages still queued in the run's
    /// interrupt channel when [`drain_pending_interrupts`] drained it — must
    /// be routed to the resumed run rather than silently dropped.
    leftover_messages: Vec<PendingInput>,
}

/// Finalize a run once its turn loop has ended: merge whatever it staged
/// (and a final extraction) into global memory, record the run's resume
/// point, write its completed store record, publish its result, and — if
/// any messages were still queued when the run's interrupt channel was
/// drained (see [`drain_pending_interrupts`]) — resume the session as a new
/// run to deliver them, once this run has fully left the registry.
///
/// Split out of [`run_session`] purely to keep that function's line count
/// down — this is still exclusively its own tail end, not a reusable step.
async fn finish_run(
    info: &mut SessionInfo,
    resources: Option<&SubAgentResources>,
    outcome: RunOutcome,
    env: &RunEnv,
) {
    let RunOutcome {
        status,
        summary,
        memory,
        recent_messages,
        leftover_messages,
    } = outcome;

    info.state = SessionState::Completing;
    transition_state(
        &env.registry,
        &env.publisher,
        info,
        SessionState::Completing,
    )
    .await;

    // Merge into global memory before recording the run as completed, so a
    // successful merge's episode id lands in the same record. A stopped run
    // merges like any other — stopping is not discarding.
    let episode_id = if let Some(res) = resources {
        let mem_env = session_memory_env(res, env.tz);
        let tag = crate::memory::types::SourceTag::session(
            info.address.to_string(),
            info.run_id.clone(),
            info.category.as_str(),
        );
        complete_session_memory(tag, &summary, recent_messages.messages(), memory, &mem_env).await
    } else {
        None
    };

    let point = resume_point(info, episode_id.clone());
    env.registry
        .record_resume_point(&info.address, point.clone());

    let transcript_path = env
        .store
        .complete_run(
            info,
            SessionState::Completed.as_str(),
            recent_messages.messages().to_vec(),
            episode_id.clone(),
        )
        .await;

    let event = build_result_event(info, status.clone(), summary, transcript_path, env.tz);
    if let Err(e) = env.publisher.publish(topics::Background, event).await {
        tracing::warn!(error = %e, "failed to publish session result to bus");
    }

    env.registry.remove(&info.address, &info.run_id);
    publish_session_event(
        &env.publisher,
        &info.address,
        &info.run_id,
        SessionEventKind::Completed { status, episode_id },
    )
    .await;
    tracing::info!("session completed");

    if !leftover_messages.is_empty() {
        tracing::warn!(
            address = %info.address,
            count = leftover_messages.len(),
            "message(s) arrived as the run was tearing down; resuming the session as a new run to deliver them"
        );
        if let Err(e) = env
            .messenger
            .resume_with_pending(&info.address, &point, &leftover_messages)
            .await
        {
            tracing::error!(
                address = %info.address,
                error = %e,
                "failed to resume session to deliver messages queued at teardown"
            );
        }
    }
}

/// Build a [`SessionMemoryEnv`] borrowing from a run's [`SubAgentResources`],
/// for the two call sites (per-turn staging, final completion) that both
/// need one from the same fields.
fn session_memory_env(res: &SubAgentResources, tz: chrono_tz::Tz) -> SessionMemoryEnv<'_> {
    SessionMemoryEnv {
        observer: &res.observer,
        merge_writer: &res.merge_writer,
        layout: &res.layout,
        episode_skip_token_floor: res.episode_skip_token_floor,
        tz,
    }
}

/// Build the content to relay to a spawned session's direct spawner for one
/// turn's outcome. A completed turn with output relays that output
/// verbatim, matching the pre-existing behavior; every other outcome — a
/// completed turn with no text output, a failed turn, or a cancelled/stopped
/// one (including a panic, reported as `Failed` — see [`recover_from_panic`])
/// — relays a clear status line instead, so the spawner is never left simply
/// not knowing what happened.
fn relay_content(address: &SessionAddress, status: &AgentResultStatus, summary: &str) -> String {
    match status {
        AgentResultStatus::Completed if !summary.is_empty() => summary.to_string(),
        AgentResultStatus::Completed
        | AgentResultStatus::Cancelled
        | AgentResultStatus::Failed { .. } => {
            format!("[Session Result] {address} — status: {status}")
        }
    }
}

/// Relay this turn's outcome to a spawned session's direct spawner, if this
/// session is `spawned` and has a spawner. Split out of [`run_session`]
/// purely to keep that function's line count down.
async fn maybe_relay_result(
    info: &SessionInfo,
    status: &AgentResultStatus,
    summary: &str,
    resources: Option<&SubAgentResources>,
    env: &RunEnv,
    recent_messages: &mut RecentMessages,
) {
    if info.category != SessionCategory::Spawned {
        return;
    }
    let Some(spawner) = info.spawner.clone() else {
        return;
    };
    let content = relay_content(&info.address, status, summary);
    let hop_count = resources.map_or(0, |res| res.hop_counter.outgoing());
    let relay_env = RelayEnv {
        messenger: &env.messenger,
        store: &env.store,
        publisher: &env.publisher,
    };
    if let Some(note) =
        relay_result_to_spawner(info, &spawner, &content, hop_count, &relay_env).await
    {
        recent_messages.push(note);
    }
}

/// Relay a spawned session's turn outcome to its direct spawner, and make any
/// delivery failure visible: logged, and appended as a system note to the
/// run's own durable transcript (via [`SessionStore::append_note`]) so it
/// survives into this run's completed record — never silently dropped, per
/// the design's result-relay rules. Treats an unreachable spawner
/// ([`DeliveryOutcome::Unknown`] — e.g. it restarted and lost its resume
/// point) as a delivery failure exactly like a hard send error, not a
/// silent success.
///
/// The failure is also published as an error event on the session's own
/// stream, so the web UI shows it on the affected session.
///
/// Returns the appended note on failure, so the caller can also fold it into
/// whatever in-memory transcript buffer it holds for the run — `None` on a
/// successful relay.
async fn relay_result_to_spawner(
    info: &SessionInfo,
    spawner: &SessionAddress,
    content: &str,
    hop_count: u32,
    env: &RelayEnv<'_>,
) -> Option<crate::inference::Message> {
    let outcome = env
        .messenger
        .send(
            spawner.as_ref(),
            info.address.clone(),
            info.category.as_str().to_string(),
            content.to_string(),
            hop_count,
        )
        .await;

    let failure = match outcome {
        Ok(DeliveryOutcome::Unknown) => {
            Some("spawner is no longer reachable (it may have restarted)".to_string())
        }
        Ok(
            DeliveryOutcome::Main
            | DeliveryOutcome::Live(_)
            | DeliveryOutcome::Resumed(_)
            | DeliveryOutcome::Queued(_),
        ) => None,
        Err(e) => Some(e.to_string()),
    };

    let reason = failure?;
    tracing::warn!(
        address = %info.address,
        spawner = %spawner,
        error = %reason,
        "failed to relay turn result to spawner"
    );
    let note_text = format!(
        "[Result Relay Failed] could not deliver this turn's result to spawner {spawner}: {reason}"
    );
    publish_session_event(
        env.publisher,
        &info.address,
        &info.run_id,
        SessionEventKind::Error {
            message: note_text.clone(),
        },
    )
    .await;
    Some(
        env.store
            .append_note(&info.run_id, info.started_at, &note_text)
            .await,
    )
}

/// Deliver this turn's output to a conversation session's own conversation.
/// A no-op for every other session (`info.conversation_target` is `None`).
///
/// Only a completed turn with real text output is delivered — a cancelled,
/// failed, or empty-output turn produces nothing to say into the
/// conversation and is left to the run's other visibility (logs, the
/// session's transcript) rather than posting an internal status line into a
/// shared chat.
async fn maybe_output_to_conversation(
    info: &SessionInfo,
    status: &AgentResultStatus,
    summary: &str,
    env: &RunEnv,
) {
    let Some(target) = info.conversation_target.as_ref() else {
        return;
    };
    if !matches!(status, AgentResultStatus::Completed) || summary.is_empty() {
        tracing::debug!(
            address = %info.address,
            status = %status,
            "conversation session turn produced no output to deliver"
        );
        return;
    }
    let event = SessionResponseEvent {
        session_address: info.address.clone(),
        conversation_id: target.conversation_id.clone(),
        content: summary.to_string(),
        attachment: None,
        timestamp: crate::time::now_local(env.tz),
    };
    if let Err(e) = env
        .publisher
        .publish(
            topics::Endpoint(EndpointName::from(target.endpoint.as_str())),
            event,
        )
        .await
    {
        tracing::error!(
            address = %info.address,
            conversation = %target.conversation_id,
            error = %e,
            "failed to publish conversation session output to the bus"
        );
    }
}

/// What [`relay_result_to_spawner`] needs besides the run and the relay
/// itself, grouped to keep its argument count down.
struct RelayEnv<'a> {
    messenger: &'a AgentMessenger,
    store: &'a SessionStore,
    publisher: &'a Publisher,
}

/// A run's identity and resources, unchanging across however many turns the
/// run has — grouped so [`run_turn`] takes one borrow of them plus its own
/// per-turn arguments (the accumulated history, this turn's kickoff, and the
/// interrupt channel), rather than each individually.
struct TurnCtx<'a> {
    info: &'a SessionInfo,
    resources: Option<&'a SubAgentResources>,
    stop_token: &'a CancellationToken,
    store: &'a SessionStore,
    /// The run's own bus publisher: every turn's lifecycle and streaming
    /// events publish through it unconditionally (the session-stream topic
    /// the web UI follows), and — via `execute_subagent`'s
    /// `conversation_output` — a conversation session's intermediate turn
    /// text additionally reaches its own conversation the same way its
    /// final output does.
    publisher: &'a Publisher,
}

/// Run one turn of a session's run, translating a missing-resources or
/// execution error into a `Failed` result rather than panicking or losing
/// the run.
///
/// `execute_subagent` returns `Ok` both when the turn finishes normally and
/// when it was stopped mid-flight (the stop token races the model call and
/// ends the turn at its next checkpoint rather than surfacing an error), so
/// an `Ok` alone cannot distinguish the two. Checking the token after the
/// fact tells them apart while still keeping whatever partial transcript
/// (left in `recent_messages`) the turn produced before it was stopped.
///
/// Brackets the turn with the same events the main agent's turns produce —
/// turn started, then the response (or an error), then turn ended — tagged
/// with the session's address, run id, and `turn_id`.
async fn run_turn(
    ctx: &TurnCtx<'_>,
    turn_id: &str,
    recent_messages: &mut RecentMessages,
    kickoff: TurnKickoff,
    interrupt_rx: &mut mpsc::Receiver<Interrupt>,
) -> (AgentResultStatus, String) {
    let publish =
        |kind| publish_session_event(ctx.publisher, &ctx.info.address, &ctx.info.run_id, kind);
    publish(SessionEventKind::TurnStarted {
        turn_id: turn_id.to_string(),
    })
    .await;

    let result = execute_turn_outcome(ctx, recent_messages, kickoff, interrupt_rx).await;

    match &result {
        (AgentResultStatus::Completed, summary) if !summary.is_empty() => {
            publish(SessionEventKind::Response {
                turn_id: turn_id.to_string(),
                content: summary.clone(),
            })
            .await;
        }
        (AgentResultStatus::Failed { error }, _) => {
            publish(SessionEventKind::Error {
                message: format!("turn failed: {error}"),
            })
            .await;
        }
        (AgentResultStatus::Completed | AgentResultStatus::Cancelled, _) => {}
    }
    publish(SessionEventKind::TurnEnded {
        turn_id: turn_id.to_string(),
    })
    .await;
    result
}

/// Execute the turn itself and classify how it ended. Split out of
/// [`run_turn`] so the event bracketing there stays readable.
async fn execute_turn_outcome(
    ctx: &TurnCtx<'_>,
    recent_messages: &mut RecentMessages,
    kickoff: TurnKickoff,
    interrupt_rx: &mut mpsc::Receiver<Interrupt>,
) -> (AgentResultStatus, String) {
    let sink = RunTranscriptSink {
        store: ctx.store,
        run_id: &ctx.info.run_id,
        started_at: ctx.info.started_at,
    };
    let conversation_output =
        ctx.info
            .conversation_target
            .as_ref()
            .map(|target| super::subagent::ConversationOutput {
                endpoint: target.endpoint.as_str(),
                conversation_id: target.conversation_id.as_str(),
            });
    let outcome = async {
        let res = ctx
            .resources
            .ok_or_else(|| anyhow::anyhow!("session run requires SubAgentResources"))?;
        let identity = SessionTurnIdentity {
            publisher: ctx.publisher,
            address: &ctx.info.address,
            run_id: &ctx.info.run_id,
        };
        execute_subagent(
            &identity,
            kickoff,
            recent_messages,
            res,
            super::subagent::TurnExecution {
                stop_token: ctx.stop_token,
                transcript_sink: Some(&sink),
                interrupt_rx,
            },
            conversation_output,
        )
        .await
    }
    .await;

    match outcome {
        Ok(summary) if ctx.stop_token.is_cancelled() => {
            tracing::info!("session turn stopped mid-flight");
            (AgentResultStatus::Cancelled, summary)
        }
        Ok(summary) => {
            tracing::info!("session turn completed");
            (AgentResultStatus::Completed, summary)
        }
        Err(e) => {
            tracing::warn!(error = %e, "session turn failed");
            (
                AgentResultStatus::Failed {
                    error: e.to_string(),
                },
                String::new(),
            )
        }
    }
}

/// Build the `AgentResultEvent` for a completed session run, computing its
/// disposition from sentinel strings the session leaves in its own summary.
///
/// `HEARTBEAT_OK` only silences a run driven by a pulse — the same rule the
/// background task bridge applied before sessions existed.
fn build_result_event(
    info: &SessionInfo,
    status: AgentResultStatus,
    summary: String,
    transcript_path: Option<std::path::PathBuf>,
    tz: chrono_tz::Tz,
) -> AgentResultEvent {
    let disposition =
        if matches!(info.trigger, EventTrigger::Pulse) && summary.contains(HEARTBEAT_OK) {
            ResultDisposition::Silent
        } else if summary.contains(HEARTBEAT_URGENT) {
            ResultDisposition::Urgent
        } else {
            ResultDisposition::Normal
        };

    AgentResultEvent {
        session_address: info.address.clone(),
        run_id: info.run_id.clone(),
        source_label: info.source_label.clone(),
        agent_skill: info.agent_skill.clone(),
        source: info.trigger.clone(),
        disposition,
        status,
        summary,
        transcript_path,
        timestamp: Utc::now().with_timezone(&tz).naive_local(),
    }
}

