#!/usr/bin/env bash
set -euo pipefail

dir=web/src/lib/generated
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

scripts/export-generated-types.sh "$work/generated"

mkdir -p "$work/index/$dir"
git ls-files -z -- "$dir" | git checkout-index --prefix="$work/index/" -z --stdin

for side in "$work/index/$dir" "$work/generated"; do
    for file in "$side"/*; do
        [ -f "$file" ] || continue
        grep -q 'This file was generated by \[ts-rs\]' "$file" || rm -f "$file"
    done
done
if ! diff -r "$work/index/$dir" "$work/generated"; then
    echo "error: $dir is out of date with the Rust types. Run 'just types' and commit the result." >&2
    exit 1
fi
