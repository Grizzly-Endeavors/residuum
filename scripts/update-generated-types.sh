#!/usr/bin/env bash
# Regenerates the ts-rs files in web/src/lib/generated from the Rust types. The
# export goes to a scratch directory first, and the checked-in files are replaced
# only once it succeeds, so a failed export leaves them as they were. A file
# carrying ts-rs's header is generated; anything without it (protocol.ts, data
# files) is hand-written or not ts-rs's to replace, and is never touched.
set -euo pipefail

dir=web/src/lib/generated
header='This file was generated by [ts-rs]'
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

scripts/export-generated-types.sh "$work/generated"

# Prints the path, relative to $1, of each file under $1 that carries the header.
generated_files() {
    (cd "$1" && find . -type f | sed 's|^\./||') | while IFS= read -r file; do
        if grep -q -F "$header" "$1/$file"; then
            printf '%s\n' "$file"
        fi
    done
}

# Copy the fresh files over first, then drop generated files the export no longer
# writes, so an interrupted copy leaves old files in place rather than none.
generated_files "$work/generated" | while IFS= read -r file; do
    mkdir -p "$dir/$(dirname "$file")"
    cp -- "$work/generated/$file" "$dir/$file"
done
generated_files "$dir" | while IFS= read -r file; do
    if [ ! -e "$work/generated/$file" ]; then
        rm -- "$dir/$file"
    fi
done
